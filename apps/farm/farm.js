const FARM_MEMBERS_KEY = 'sx_farm_members';

function getFarmMembers() {
    try {
        const raw = localStorage.getItem(FARM_MEMBERS_KEY);
        return raw ? JSON.parse(raw) : [];
    } catch (e) {
        return [];
    }
}

function saveFarmMembers(members) {
    localStorage.setItem(FARM_MEMBERS_KEY, JSON.stringify(members));
}

function loadSocialPanel() {
    const membersList = document.getElementById('farm-members-list');
    
    if (membersList) {
        membersList.innerHTML = '';
        const members = getFarmMembers();
        
        if (members.length > 0) {
            members.forEach((member, index) => {
                const item = document.createElement('div');
                item.className = 'grid-item active-press';
                item.onclick = () => openCharacterComment(member, index);
                
                const roleText = t(`roles.${member.role}`) || member.role;
                const avatarHtml = member.avatar 
                    ? `<img src="${member.avatar}" class="item-avatar" alt="${member.name || 'Character'}">` 
                    : `<div class="item-avatar-placeholder"><span class="material-symbols-outlined" style="font-size:24px;color:var(--parchment);">person</span></div>`;
                
                item.innerHTML = `
                    ${avatarHtml}
                    <span class="item-name">${member.name || 'Unknown'}</span>
                    <span class="item-role" style="font-size:9px;color:var(--primary-container);display:block;margin-top:2px;">${roleText}</span>
                `;
                membersList.appendChild(item);
            });
        } else {
            membersList.innerHTML = '<p class="empty-hint">' + t('noCharacters') + '</p>';
        }
    }
}

function openImportModal() {
    const modal = document.getElementById('import-modal');
    const select = document.getElementById('import-char-select');
    const roleSelect = document.getElementById('import-role-select');
    
    if (!modal || !select || !roleSelect) return;
    
    select.innerHTML = '';
    
    const charsRaw = localStorage.getItem('sx_characters');
    const npcsRaw = localStorage.getItem('sx_npcs');
    const chars = charsRaw ? JSON.parse(charsRaw) : [];
    const npcs = npcsRaw ? JSON.parse(npcsRaw) : [];
    const existingMembers = getFarmMembers();
    const existingIds = new Set(existingMembers.map(m => m.id));
    
    const allChars = [
        ...chars.map(c => ({ ...c, isNpc: false })),
        ...npcs.map(n => ({ ...n, isNpc: true }))
    ];
    
    const availableChars = allChars.filter(c => c.id && !existingIds.has(c.id));
    
    if (availableChars.length === 0) {
        select.innerHTML = `<option value="">${t('noCharacters')}</option>`;
    } else {
        select.innerHTML = '<option value="">' + t('selectCharacter') + '</option>';
        availableChars.forEach(char => {
            const opt = document.createElement('option');
            opt.value = JSON.stringify({ id: char.id, isNpc: char.isNpc });
            opt.textContent = `${char.name || 'Unknown'} ${char.isNpc ? '(NPC)' : ''}`;
            select.appendChild(opt);
        });
    }
    
    roleSelect.innerHTML = '';
    const roles = ['partner', 'neighbor', 'merchant', 'visitor', 'helper'];
    roles.forEach(role => {
        const opt = document.createElement('option');
        opt.value = role;
        opt.textContent = t(`roles.${role}`) || role;
        roleSelect.appendChild(opt);
    });
    
    modal.classList.add('active');
}

function closeImportModal() {
    const modal = document.getElementById('import-modal');
    if (modal) modal.classList.remove('active');
}

function confirmImport() {
    const select = document.getElementById('import-char-select');
    const roleSelect = document.getElementById('import-role-select');
    
    if (!select || !roleSelect) return;
    
    const selectedValue = select.value;
    if (!selectedValue) return;
    
    const { id, isNpc } = JSON.parse(selectedValue);
    const role = roleSelect.value || 'visitor';
    
    const charsRaw = localStorage.getItem(isNpc ? 'sx_npcs' : 'sx_characters');
    const chars = charsRaw ? JSON.parse(charsRaw) : [];
    const char = chars.find(c => c.id === id);
    
    if (!char) return;
    
    const members = getFarmMembers();
    members.push({
        id: char.id,
        name: char.name,
        avatar: char.avatar,
        personality: char.personality,
        background: char.background,
        role: role,
        isNpc: isNpc
    });
    
    saveFarmMembers(members);
    closeImportModal();
    loadSocialPanel();
}

function openCharacterComment(member, index) {
    const modal = document.getElementById('character-comment-modal');
    const avatar = document.getElementById('comment-avatar');
    const nameEl = document.getElementById('comment-name');
    const roleEl = document.getElementById('comment-role');
    const textEl = document.getElementById('comment-text');
    
    if (!modal) return;
    
    window.currentCommentChar = member;
    window.currentCommentIndex = index;
    
    if (avatar) {
        avatar.src = member.avatar || '';
        avatar.style.display = member.avatar ? 'block' : 'none';
    }
    
    if (nameEl) {
        nameEl.textContent = member.name || 'Unknown';
    }
    
    if (roleEl) {
        roleEl.textContent = t(`roles.${member.role}`) || member.role;
    }
    
    if (textEl) {
        textEl.innerHTML = '<div class="comment-loading"><span class="material-symbols-outlined" style="animation: spin 1s linear infinite;">sync</span><span>Loading comment...</span></div>';
    }
    
    modal.classList.add('active');
    
    generateCharacterComment(member);
}

function closeCharacterComment() {
    const modal = document.getElementById('character-comment-modal');
    if (modal) {
        modal.classList.remove('active');
    }
}

function removeFarmMember() {
    const char = window.currentCommentChar;
    if (!char) return;
    
    const members = getFarmMembers();
    const idx = members.findIndex(m => m.id === char.id);
    if (idx === -1) return;
    
    members.splice(idx, 1);
    saveFarmMembers(members);
    closeCharacterComment();
    loadSocialPanel();
}

async function generateCharacterComment(member) {
    const textEl = document.getElementById('comment-text');
    
    try {
        const apis = JSON.parse(localStorage.getItem('api_configs') || '[]');
        const activeIndex = Number(localStorage.getItem('sx_active_api')) || 0;
        const config = apis[activeIndex] || apis[0];
        
        if (!config || !config.url) {
            textEl.innerHTML = '<p style="color: var(--error);">No API configured. Please set up API in Settings.</p>';
            return;
        }
        
        const seasonNames = t('seasonNames');
        const currentSeasonIdx = Math.floor((FarmGame.state.day - 1) / 28) % 4;
        const currentSeason = seasonNames[currentSeasonIdx] || 'Spring';
        const dayInSeason = ((FarmGame.state.day - 1) % 28) + 1;
        
        const farmStatus = {
            season: currentSeason,
            day: dayInSeason,
            gold: FarmGame.state.gold,
            level: FarmGame.state.level,
            fields: FarmGame.state.fields.filter(f => f).length,
            weather: FarmGame.state.weather
        };
        
        const roleDescriptions = {
            partner: 'You are a co-owner of this farm. You actively participate in farm decisions and share the profits.',
            neighbor: 'You own the neighboring farm. You sometimes compete but mostly help each other.',
            merchant: 'You are a traveling merchant who visits the farm to buy and sell goods.',
            visitor: 'You are a curious visitor exploring the farm.',
            helper: 'You are a farm helper who assists with daily tasks.'
        };
        
        const personality = member.personality || member.background || '';
        const roleText = t(`roles.${member.role}`) || member.role;
        const roleDesc = roleDescriptions[member.role] || roleDescriptions.visitor;
        
        const systemPrompt = `${personality}\n\n${roleDesc}\n\nYou are ${member.name}, a ${roleText} at this pixel farm. Stay in character and give helpful, friendly comments.`;
        
        const userPrompt = `You are visiting a pixel farm. Here's the current farm status:
- Season: ${farmStatus.season}, Day ${farmStatus.day}
- Gold: ${farmStatus.gold}g
- Level: ${farmStatus.level}
- Active fields: ${farmStatus.fields}
- Weather: ${farmStatus.weather}

Please give a short, friendly comment (2-3 sentences) about what you see or what you think the farmer should do. Be in character as ${member.name}, the ${roleText}.`;

        const targetUrl = config.url.endsWith('/chat/completions') 
            ? config.url 
            : config.url.replace(/\/$/, '') + '/chat/completions';
        
        const response = await fetch(targetUrl, {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Authorization': config.key ? `Bearer ${config.key}` : ''
            },
            body: JSON.stringify({
                model: config.model || 'gpt-3.5-turbo',
                messages: [
                    { role: 'system', content: systemPrompt },
                    { role: 'user', content: userPrompt }
                ],
                temperature: 0.8,
                max_tokens: 150
            })
        });
        
        if (!response.ok) {
            throw new Error(`API error: ${response.status}`);
        }
        
        const data = await response.json();
        const comment = data.choices?.[0]?.message?.content || 'Interesting farm you have here!';
        
        if (textEl) {
            textEl.innerHTML = `<p class="comment-text">"${comment}"</p>`;
        }
        
    } catch (e) {
        console.error('Failed to generate comment:', e);
        if (textEl) {
            textEl.innerHTML = `<p style="color: var(--error);">Failed to generate comment. Please check your API settings.</p>`;
        }
    }
}

