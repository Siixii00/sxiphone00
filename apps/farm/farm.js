const CROP_EMOJIS = {
    turnip: ['🌱', '🌿', '🥕'],
    tomato: ['🌱', '🌿', '🍅'],
    pumpkin: ['🌱', '🌿', '🎃'],
    corn: ['🌱', '🌿', '🌽'],
    strawberry: ['🌱', '🌿', '🍓'],
    sunflower: ['🌱', '🌻', '🌻'],
    tulip: ['🌱', '🌷', '🌷']
};

const GRID_SIZE = 8;

function getFarmLang() {
    const lang = localStorage.getItem('sxiphone_lang') || 'zh-Hant';
    if (lang.startsWith('zh-CN') || lang.startsWith('zh-SG')) return 'zh-Hans';
    if (lang.startsWith('zh')) return 'zh-Hant';
    if (lang.startsWith('ja')) return 'ja';
    if (lang.startsWith('ko')) return 'ko';
    return 'en';
}

function t(key, replacements = {}) {
    const lang = getFarmLang();
    const i18nData = FARM_I18N[lang] || FARM_I18N['en'];
    let text = key.split('.').reduce((obj, k) => obj?.[k], i18nData) || key;
    Object.entries(replacements).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, v);
    });
    return text;
}

const FarmGame = {
    state: {
        gold: 500,
        day: 1,
        level: 1,
        totalEarnings: 0,
        weather: 'sunny',
        currentTool: 'till',
        fields: [],
        animals: [],
        inventory: {
            seeds: { turnip: 5, tomato: 0, pumpkin: 0, corn: 0, strawberry: 0, sunflower: 0, tulip: 0 },
            products: { Egg: 0, Milk: 0, Wool: 0 }
        },
        selectedCrop: 'turnip',
        hasSprinkler: false,
        barnCapacity: 2,
        energy: 270,
        maxEnergy: 300
    },
    
    init() {
        this.load();
        
        const loadingBar = document.getElementById('loading-bar');
        if (loadingBar) {
            loadingBar.style.width = '50%';
        }
        
        for (let i = 0; i < GRID_SIZE; i++) {
            if (!this.state.fields[i]) {
                this.state.fields[i] = null;
            }
        }
        
        if (loadingBar) {
            loadingBar.style.width = '80%';
        }
        
        this.renderCropGrid();
        this.updateUI();
        
        if (loadingBar) {
            loadingBar.style.width = '100%';
        }
        
        this.hideLoading();
    },
    
    save() {
        try {
            localStorage.setItem('sx_farm_save', JSON.stringify(this.state));
        } catch (e) {}
    },
    
    load() {
        try {
            const saved = localStorage.getItem('sx_farm_save');
            if (saved) {
                const loaded = JSON.parse(saved);
                this.state = { ...this.state, ...loaded };
            }
        } catch (e) {}
    },
    
    hideLoading() {
        const loading = document.getElementById('farm-loading');
        if (loading) {
            loading.classList.add('fade-out');
            setTimeout(() => loading.style.display = 'none', 500);
        }
    },
    
    renderCropGrid() {
        const grid = document.getElementById('crop-grid');
        if (!grid) return;
        
        grid.innerHTML = '';
        
        for (let i = 0; i < GRID_SIZE; i++) {
            const field = this.state.fields[i];
            const slot = document.createElement('div');
            slot.className = 'crop-slot wooden-panel active-press';
            slot.dataset.index = i;
            slot.onclick = () => this.handleFieldClick(i);
            
            if (field && field.crop) {
                const cropData = FARM_DATA.CROPS[field.crop];
                const stage = Math.min(Math.floor(field.growth / cropData.growDays * 2), 2);
                const emoji = CROP_EMOJIS[field.crop]?.[stage] || '🌱';
                const daysLeft = cropData.growDays - field.growth;
                const isReady = daysLeft <= 0;
                
                slot.innerHTML = `
                    <div class="parchment-card">
                        <span class="crop-emoji">${emoji}</span>
                        ${isReady ? '<span class="material-symbols-outlined crop-ready" style="font-variation-settings: \'FILL\' 1;">check_circle</span>' : `<span class="crop-days">${daysLeft}d</span>`}
                    </div>
                `;
            } else if (field && field.tilled) {
                slot.innerHTML = `
                    <div class="parchment-card">
                        <span class="crop-emoji" style="opacity: 0.5;">🌿</span>
                    </div>
                `;
            } else {
                slot.classList.add('empty');
                slot.innerHTML = `
                    <div class="parchment-card">
                        <span class="material-symbols-outlined crop-placeholder" style="font-size: 24px;">add_task</span>
                    </div>
                `;
            }
            
            grid.appendChild(slot);
        }
    },
    
    handleFieldClick(index) {
        const field = this.state.fields[index];
        const tool = this.state.currentTool;
        
        switch (tool) {
            case 'till':
                if (!field || !field.tilled) {
                    this.state.fields[index] = { tilled: true, watered: false, crop: null, growth: 0 };
                }
                break;
            case 'plant':
                if (field?.tilled && !field.crop) {
                    const crop = this.state.selectedCrop;
                    if (this.state.inventory.seeds[crop] > 0) {
                        this.state.fields[index].crop = crop;
                        this.state.fields[index].growth = 0;
                        this.state.inventory.seeds[crop]--;
                    }
                }
                break;
            case 'water':
                if (field?.tilled) {
                    this.state.fields[index].watered = true;
                }
                break;
            case 'harvest':
                if (field?.crop) {
                    const cropData = FARM_DATA.CROPS[field.crop];
                    if (field.growth >= cropData.growDays) {
                        this.state.gold += cropData.sellPrice;
                        this.state.totalEarnings += cropData.sellPrice;
                        this.state.fields[index] = null;
                        this.checkLevelUp();
                    }
                }
                break;
        }
        
        this.save();
        this.renderCropGrid();
        this.updateUI();
    },
    
    waterAll() {
        for (let i = 0; i < GRID_SIZE; i++) {
            const field = this.state.fields[i];
            if (field?.tilled) {
                field.watered = true;
            }
        }
        this.save();
        this.renderCropGrid();
    },
    
    endDay() {
        for (let i = 0; i < GRID_SIZE; i++) {
            const field = this.state.fields[i];
            if (field?.crop && (field.watered || this.state.weather === 'rainy' || this.state.weather === 'stormy')) {
                field.growth++;
            }
            if (field) {
                field.watered = this.state.hasSprinkler;
            }
        }
        
        this.state.day++;
        this.calculateWeather();
        this.checkLevelUp();
        this.save();
        this.renderCropGrid();
        this.updateUI();
    },
    
    calculateWeather() {
        const h = Math.floor(Math.random() * 256);
        if (h < 180) this.state.weather = 'sunny';
        else if (h < 220) this.state.weather = 'cloudy';
        else if (h < 250) this.state.weather = 'rainy';
        else this.state.weather = 'stormy';
    },
    
    checkLevelUp() {
        const thresholds = FARM_DATA.LEVEL_THRESHOLDS;
        for (let i = thresholds.length - 1; i >= 0; i--) {
            if (this.state.totalEarnings >= thresholds[i] && this.state.level < i + 1) {
                this.state.level = i + 1;
                break;
            }
        }
    },
    
    updateUI() {
        const goldDisplay = document.getElementById('gold-display');
        if (goldDisplay) goldDisplay.textContent = this.state.gold + 'g';
        
        const dayInSeason = ((this.state.day - 1) % 28) + 1;
        const progressPercent = Math.round((dayInSeason / 28) * 100);
        
        const seasonProgress = document.getElementById('farm-season-progress');
        if (seasonProgress) seasonProgress.style.width = progressPercent + '%';
        
        const farmDayDisplay = document.getElementById('farm-day-display');
        if (farmDayDisplay) farmDayDisplay.textContent = `Day ${dayInSeason} / 28`;
        
        const seasonNames = t('seasonNames');
        const currentSeasonIdx = Math.floor((this.state.day - 1) / 28) % 4;
        const currentSeason = seasonNames[currentSeasonIdx] || 'Spring';
        
        const farmSeasonName = document.getElementById('farm-season-name');
        if (farmSeasonName) farmSeasonName.textContent = `Season: ${currentSeason}`;
        
        const seasonTimeEl = document.getElementById('season-time-display');
        if (seasonTimeEl) {
            const hour = 6 + Math.floor((this.state.day * 17) % 12);
            seasonTimeEl.textContent = t('seasonTime', { day: dayInSeason, time: `${hour.toString().padStart(2, '0')}:00` });
        }
        
        const seasonHint = document.getElementById('farm-season-hint');
        if (seasonHint) seasonHint.textContent = t('seasonProgress');
        
        const houseLevel = document.getElementById('house-level');
        if (houseLevel) houseLevel.textContent = this.state.level;
        
        const energyStat = document.getElementById('energy-stat');
        if (energyStat) energyStat.textContent = this.state.energy;
        
        updateInventoryPanel();
        updateToolHighlight();
    }
};

function updateToolHighlight() {
    document.querySelectorAll('.tool-slot').forEach(slot => {
        slot.classList.remove('active');
        if (slot.dataset.tool === FarmGame.state.currentTool) {
            slot.classList.add('active');
        }
    });
}

function setTool(tool) {
    FarmGame.state.currentTool = tool;
    updateToolHighlight();
    
    if (tool === 'plant') {
        openCropSelect();
    }
}

function waterAll() {
    FarmGame.waterAll();
}

function openShop() {
    const modal = document.getElementById('shop-modal');
    const container = document.getElementById('shop-items');
    container.innerHTML = '';
    
    FARM_DATA.SHOP_ITEMS.seeds.forEach(cropKey => {
        const crop = FARM_DATA.CROPS[cropKey];
        if (FarmGame.state.level >= crop.unlockLevel) {
            const item = document.createElement('div');
            item.className = 'shop-item active-press';
            item.innerHTML = `<h3>${crop.nameZh}</h3><p>${crop.seedPrice}G</p>`;
            item.onclick = () => buySeed(cropKey);
            container.appendChild(item);
        }
    });
    
    modal.classList.add('active');
}

function closeShop() {
    document.getElementById('shop-modal').classList.remove('active');
}

function buySeed(cropKey) {
    const crop = FARM_DATA.CROPS[cropKey];
    if (FarmGame.state.gold >= crop.seedPrice) {
        FarmGame.state.gold -= crop.seedPrice;
        FarmGame.state.inventory.seeds[cropKey]++;
        FarmGame.save();
        FarmGame.updateUI();
    }
}

function openCropSelect() {
    const modal = document.getElementById('crop-select-modal');
    const container = document.getElementById('crop-options');
    container.innerHTML = '';
    
    Object.entries(FarmGame.state.inventory.seeds).forEach(([key, count]) => {
        if (count > 0) {
            const crop = FARM_DATA.CROPS[key];
            const item = document.createElement('div');
            item.className = 'crop-option active-press';
            item.innerHTML = `<h3>${crop.nameZh}</h3><p>x${count}</p>`;
            item.onclick = () => selectCrop(key);
            container.appendChild(item);
        }
    });
    
    if (container.children.length === 0) {
        container.innerHTML = '<p class="empty-hint">No seeds available</p>';
    }
    
    modal.classList.add('active');
}

function closeCropSelect() {
    document.getElementById('crop-select-modal').classList.remove('active');
}

function selectCrop(cropKey) {
    FarmGame.state.selectedCrop = cropKey;
    closeCropSelect();
}

