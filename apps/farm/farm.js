function updateInventoryPanel() {
    const seedsList = document.getElementById('inventory-seeds-list');
    const productsList = document.getElementById('inventory-products-list');
    
    if (seedsList) {
        seedsList.innerHTML = '';
        Object.entries(FarmGame.state.inventory.seeds).forEach(([key, count]) => {
            if (count > 0) {
                const crop = FARM_DATA.CROPS[key];
                const item = document.createElement('div');
                item.className = 'grid-item active-press';
                item.innerHTML = `<span class="item-name">${crop?.nameZh || key}</span><span class="item-count">x${count}</span>`;
                seedsList.appendChild(item);
            }
        });
        if (seedsList.children.length === 0) {
            seedsList.innerHTML = '<p class="empty-hint">No seeds</p>';
        }
    }
    
    if (productsList) {
        productsList.innerHTML = '';
        Object.entries(FarmGame.state.inventory.products).forEach(([key, count]) => {
            if (count > 0) {
                const item = document.createElement('div');
                item.className = 'grid-item active-press';
                item.innerHTML = `<span class="item-name">${key}</span><span class="item-count">x${count}</span>`;
                productsList.appendChild(item);
            }
        });
        if (productsList.children.length === 0) {
            productsList.innerHTML = '<p class="empty-hint">No products</p>';
        }
    }
}

